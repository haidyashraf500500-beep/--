def main() -> None:
    print(f"PDF path: {PDF_PATH}")
    if os.path.exists(PDF_PATH):
        raw_text = extract_pdf_text(PDF_PATH)
        print(f"Extracted raw PDF text: {len(raw_text.split())} words "
              f"(kept for reference only; DOCUMENTS below is what the pipeline uses)")
    else:
        print("Source PDF not found next to this file - DOCUMENTS below is still usable on its own.")

    print(f"\nCurated sub-documents: {len(DOCUMENTS)}")
    for doc in DOCUMENTS:
        print(f"  [{doc['document_id']}] ({doc['sector']} / {doc['doc_type']}) {doc['title']} "
              f"- {len(doc['text'].split())} words")


if __name__ == "__main__":
    main()
