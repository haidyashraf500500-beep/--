"""
01_documents.py
================
Stage 1 of the pipeline: raw documents.

documents -> preprocessing -> chunking -> vector representation -> vector store
-> context retrieval -> prompting -> Streamlit UI

This file is the ONLY place that touches the source PDF. Every later stage
imports `DOCUMENTS` from this file instead of re-reading the PDF, so the whole
pipeline always works from the exact same source data.

The source report ("الاحوال_المدنيه.pdf") covers several unrelated government
sectors (civil status, passports, traffic, real-estate registry, supply/ration
cards). Splitting it into sector-labeled sub-documents up front is what lets
retrieval later distinguish "national ID fees" from "passport fees", etc.
"""

import os
